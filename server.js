import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { X509Certificate } from 'node:crypto';
import express from 'express';
import cors from 'cors';
import { Pool } from 'pg';
import bcrypt from 'bcryptjs';
import jwt from 'jsonwebtoken';

const serverDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootDirectory = path.resolve(serverDirectory, '..');
const settingsText = await fs.readFile(path.join(rootDirectory, 'PostgreSQL_ DB.txt'), 'utf8');
const settings = {};
const settingNames = {
  username: 'username',
  user: 'username',
  password: 'password',
  hostname: 'host',
  host: 'host',
  port: 'port',
  'database name': 'database',
  database: 'database',
  'table name': 'table',
  table: 'table',
};
const lines = settingsText.split(/\r?\n/);
for (let index = 0; index < lines.length; index += 1) {
  const match = lines[index].trim().match(/^(?:PostgreSQL\s+)?(username|user|password|hostname|host|port|database(?:\s+name)?|table(?:\s+name)?)\s*:?\s*(.*)$/i);
  if (!match) continue;

  let value = match[2].trim();
  if (!value) {
    index += 1;
    while (index < lines.length && !lines[index].trim()) index += 1;
    value = lines[index]?.trim() ?? '';
  }
  settings[settingNames[match[1].toLowerCase()]] = value;
}

for (const name of ['username', 'password', 'host', 'port', 'database']) {
  if (!settings[name]) throw new Error(`PostgreSQL_ DB.txt must contain a ${name} setting`);
}
const databasePort = Number(settings.port);
if (!Number.isInteger(databasePort) || databasePort < 1 || databasePort > 65535) {
  throw new Error('PostgreSQL_ DB.txt must contain a valid port');
}

const tableName = settings.table || 'User_Info';
if (!tableName || !/^[a-zA-Z0-9_]+$/.test(tableName)) {
  throw new Error('PostgreSQL_ DB.txt must contain a valid table name');
}

const rejectUnauthorized = process.env.PGSSL_REJECT_UNAUTHORIZED !== 'false';
const jwtSecret = process.env.JWT_SECRET ?? 'local-development-only-change-this-secret';
const caCertificate = await fs.readFile(path.join(rootDirectory, 'ca.pem'), 'utf8');
new X509Certificate(caCertificate);

const pool = new Pool({
  host: settings.host,
  user: settings.username,
  password: settings.password,
  port: databasePort,
  database: settings.database,
  ssl: { ca: caCertificate, rejectUnauthorized },
});

await pool.query(`CREATE TABLE IF NOT EXISTS "${tableName}" (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
)`);

const app = express();
app.use(cors());
app.use(express.json({ limit: '10kb' }));

app.get('/api/health', (_request, response) => response.json({ ok: true }));

function authenticate(request, response, next) {
  const authorization = request.get('authorization') ?? '';
  const token = authorization.startsWith('Bearer ') ? authorization.slice(7) : null;
  if (!token) return response.status(401).json({ message: 'Authentication required.' });

  try {
    request.user = jwt.verify(token, jwtSecret);
    return next();
  } catch {
    return response.status(401).json({ message: 'Your session has expired. Please sign in again.' });
  }
}

app.post('/api/register', async (request, response) => {
  const { name, email, password } = request.body ?? {};
  if (typeof name !== 'string' || name.trim().length < 2 || typeof email !== 'string' || typeof password !== 'string' || password.length < 8) {
    return response.status(400).json({ message: 'Name, valid email, and an 8-character password are required.' });
  }

  try {
    const normalizedEmail = email.trim().toLowerCase();
    const existingUsers = await pool.query(`SELECT id FROM "${tableName}" WHERE email = $1 LIMIT 1`, [normalizedEmail]);
    if (existingUsers.rows.length > 0) {
      return response.status(409).json({ message: 'This email is already registered. Please use another email or sign in.' });
    }

    const passwordHash = await bcrypt.hash(password, 12);
    await pool.query(`INSERT INTO "${tableName}" (name, email, password_hash, created_at) VALUES ($1, $2, $3, CURRENT_TIMESTAMP)`, [name.trim(), normalizedEmail, passwordHash]);
    return response.status(201).json({ message: 'Account created. You can now sign in.' });
  } catch (error) {
    if (error.code === '23505') return response.status(409).json({ message: 'An account with that email already exists.' });
    console.error(error);
    return response.status(500).json({ message: 'Could not create the account.' });
  }
});

app.post('/api/login', async (request, response) => {
  const { email, password } = request.body ?? {};
  if (typeof email !== 'string' || typeof password !== 'string') {
    return response.status(400).json({ message: 'Email and password are required.' });
  }

  try {
    const result = await pool.query(`SELECT id, name, email, password_hash FROM "${tableName}" WHERE email = $1 LIMIT 1`, [email.trim().toLowerCase()]);
    const user = result.rows[0];
    if (!user || !(await bcrypt.compare(password, user.password_hash))) {
      return response.status(401).json({ message: 'Email or password is incorrect.' });
    }
    const token = jwt.sign({ id: user.id }, jwtSecret, { expiresIn: '8h' });
    return response.json({ message: `Welcome back, ${user.name}.`, token, user: { id: user.id, name: user.name, email: user.email } });
  } catch (error) {
    console.error(error);
    return response.status(500).json({ message: 'Could not complete sign in.' });
  }
});

app.patch('/api/me', authenticate, async (request, response) => {
  const { name, password } = request.body ?? {};
  if (typeof name !== 'string' || name.trim().length < 2) {
    return response.status(400).json({ message: 'Name must contain at least 2 characters.' });
  }
  if (password !== undefined && (typeof password !== 'string' || password.length < 8)) {
    return response.status(400).json({ message: 'A new password must contain at least 8 characters.' });
  }

  try {
    if (password) {
      const passwordHash = await bcrypt.hash(password, 12);
      await pool.query(`UPDATE "${tableName}" SET name = $1, password_hash = $2 WHERE id = $3`, [name.trim(), passwordHash, request.user.id]);
    } else {
      await pool.query(`UPDATE "${tableName}" SET name = $1 WHERE id = $2`, [name.trim(), request.user.id]);
    }
    return response.json({ message: 'Your account has been updated.', user: { name: name.trim() } });
  } catch (error) {
    console.error(error);
    return response.status(500).json({ message: 'Could not update your account.' });
  }
});

const port = Number(process.env.PORT ?? 3000);
app.listen(port, () => console.log(`Auth API listening on http://localhost:${port}`));
